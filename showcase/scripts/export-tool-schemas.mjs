/**
 * Exports the Agent Desk's live WebMCP tool schemas to webmcp/tools.schema.json.
 *
 * The schemas are captured from the page as it actually registers them — not
 * hand-copied — so the file that feeds Google's `webmcp-evals` harness can
 * never drift from what an agent really sees.
 */
import { chromium } from '@playwright/test';
import { writeFileSync } from 'node:fs';

const EXEC = process.env.CHROMIUM_PATH || undefined;
const BASE = process.env.DESK_URL || 'http://localhost:4321/agent-terminal';
const OUT = new URL('../webmcp/tools.schema.json', import.meta.url);

const browser = await chromium.launch(EXEC ? { executablePath: EXEC } : {});
const page = await browser.newPage();

await page.addInitScript(() => {
  const tools = new Map();
  Object.defineProperty(document, 'modelContext', {
    configurable: true,
    value: {
      async registerTool(tool, options) {
        tools.set(tool.name, tool);
        options?.signal?.addEventListener('abort', () => tools.delete(tool.name));
      },
      // Sync view, so the waiter below can't resolve on a pending Promise.
      list: () => [...tools.keys()],
      // Mirrors the spec's getTools() shape closely enough for schema export.
      getTools: async () =>
        [...tools.values()].map((t) => ({
          name: t.name,
          description: t.description,
          inputSchema: t.inputSchema,
          annotations: t.annotations ?? {},
        })),
    },
  });
});

// The desk prices through the public preview endpoint; stub it so schema export
// never depends on the network.
await page.route('**/public/swap/**', (route) =>
  route.fulfill({ status: 200, contentType: 'application/json', body: '{"chains":[]}' }),
);

await page.goto(BASE, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => document.modelContext.list().length > 0);

// Surface the two conditional tools too: they are part of the contract even
// though they only exist while the human's state unlocks them.
const staticTools = await page.evaluate(() => document.modelContext.getTools());

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/export-tool-schemas.mjs from the live page. Do not hand-edit. ' +
        'request_override and open_signing_handoff are registered dynamically and appear only ' +
        'once the human blocks or approves something, so they are absent from this static export.',
      tools: staticTools,
    },
    null,
    2,
  )}\n`,
);
console.log(`exported ${staticTools.length} tool schemas -> webmcp/tools.schema.json`);
await browser.close();
