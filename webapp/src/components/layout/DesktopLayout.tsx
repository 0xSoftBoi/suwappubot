export function DesktopLayout({ children }: { children: React.ReactNode }) {
  const navigate = useNavigate()
  const location = useLocation()

  const activeItem = sidebarItems.find((item) =>
    location.pathname.startsWith(item.path)
  )?.id || 'home'

  return (
    <div className="flex h-screen bg-suwappu-bg overflow-hidden">
      {/* Sidebar */}
      <aside className="w-56 flex-shrink-0 bg-white/80 backdrop-blur-md border-r border-suwappu-sakura-mid/20 flex flex-col">
        {/* App title with drag region for hidden titlebar */}
        <div
          className="h-14 flex items-center px-4 border-b border-suwappu-sakura-mid/10"
          style={{ WebkitAppRegion: 'drag' } as React.CSSProperties}
        >
          <span className="font-display text-xl text-suwappu-magenta-mid">
            Suwappu
          </span>
        </div>

        {/* Nav items */}
        <nav className="flex-1 overflow-y-auto py-2 px-2">
          {sidebarItems.map((item) => (
            <button
              key={item.id}
              onClick={() => navigate(item.path)}
              className={`w-full flex items-center gap-3 px-3 py-2.5 rounded-suwappu-md text-sm font-heading font-medium transition-colors mb-0.5 ${
                activeItem === item.id
                  ? 'bg-suwappu-sakura-100 text-suwappu-magenta-mid'
                  : 'text-suwappu-text-secondary hover:bg-suwappu-sakura-50 hover:text-suwappu-text'
              }`}
            >
              {item.icon}
              {item.label}
            </button>
          ))}
        </nav>
      </aside>

      {/* Main content */}
      <main className="flex-1 overflow-y-auto">
        {children}
      </main>

      {/* Desktop-exclusive overlay components */}
      <ClipboardLookup />
      <QuickSwap />
      <LaunchFeed />
    </div>
  )
}
