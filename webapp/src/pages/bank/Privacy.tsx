import { useRef, useState } from 'react'
import { useMutation, useQuery } from '@tanstack/react-query'
import { bank, bankErrorText } from '../../lib/bankApi'
import { scanLocally, type LocalMatch } from '../../lib/stealthScan'
import { BankPage, Btn, Card, ErrorBox, Field, Input, Row, SectionTitle } from '../../components/bank/BankUI'
import { a11yToast } from '@/lib/a11yToast'

const copy = (t: string) => navigator.clipboard.writeText(t).then(() => a11yToast.success('Copied'), () => a11yToast.error('Could not copy'))
const toHexBlock = (v: string): string | null => { const t = v.trim(); if (/^0x[0-9a-fA-F]+$/.test(t)) return t; return /^\d{1,15}$/.test(t) ? `0x${Number(t).toString(16)}` : null }
const show = (v: unknown): string => (typeof v === 'string' ? v : JSON.stringify(v))

const INIT = { running: false, done: false, cancelled: false, at: null as string | null, windows: 0, seen: 0, matches: [] as LocalMatch[], error: null as string | null }

/** Stealth addresses (ERC-5564 style): keys are generated by the API ONCE and never stored; the user must save them. */
export function Privacy() {
  const meta = useMutation({ mutationFn: () => bank.metaAddress() })
  const [meta2, setMeta2] = useState(''); const [ref, setRef] = useState('')
  const payout = useMutation({ mutationFn: () => bank.privatePayout({ payeeMetaAddress: meta2.trim(), payoutRef: ref.trim() }) })
  const [chain, setChain] = useState('base'); const [from, setFrom] = useState(''); const [vk, setVk] = useState(''); const [sk, setSk] = useState('')
  const scan = useMutation({ mutationFn: () => bank.privacyScan({ chain: chain.trim(), fromBlock: toHexBlock(from) ?? from.trim(), viewPrivateKey: vk.trim(), spendPublicKey: sk.trim() }) })
  const cancelRef = useRef(false)
  const [local, setLocal] = useState(INIT)
  const runLocal = async () => {
    cancelRef.current = false
    setLocal({ ...INIT, running: true })
    let next: string | null = toHexBlock(from)
    let windows = 0; let seen = 0; const matches: LocalMatch[] = []
    try {
      while (next && !cancelRef.current) {
        setLocal((l) => ({ ...l, at: String(parseInt(next as string, 16)), windows, seen, matches: [...matches] }))
        const r = await bank.privacyAnnouncements({ chain: chain.trim(), fromBlock: next })
        const anns = r.announcements ?? r.entries ?? []
        seen += anns.length; windows += 1
        matches.push(...scanLocally(anns, vk.trim(), sk.trim()))
        const c = r.nextCursor
        const nb = c === null || c === undefined ? null : `0x${Number(c).toString(16)}`
        if (nb !== null && nb === next) throw new Error('The server did not advance the scan range.')
        next = nb
      }
      setLocal({ running: false, done: true, cancelled: cancelRef.current, at: null, windows, seen, matches, error: null })
    } catch (e) {
      setLocal({ running: false, done: false, cancelled: false, at: null, windows, seen, matches, error: e instanceof Error && !(e as { code?: string }).code && !('status' in e) ? e.message : bankErrorText(e) })
    }
  }
  const exp = useQuery({ queryKey: ['bank', 'compliance-export'], queryFn: async () => (await bank.complianceExport()).export, enabled: false, retry: 0 })
  const [armed, setArmed] = useState(false)
  const keys = (meta.data?.keys ?? {}) as Record<string, unknown>
  const download = () => {
    const el = document.createElement('a')
    el.href = URL.createObjectURL(new Blob([JSON.stringify(exp.data, null, 2)], { type: 'application/json' }))
    el.download = 'compliance-export.json'; el.click(); URL.revokeObjectURL(el.href)
  }
  return (
    <BankPage title="Privacy">
      <SectionTitle>Stealth address setup</SectionTitle>
      <Card className="space-y-2">
        <p className="text-xs text-suwappu-text-secondary">Create a stealth meta-address so senders can pay you at one-time addresses. The private keys are shown once and are never stored by Suwappu. Save them somewhere safe before leaving this screen.</p>
        {meta.isError && <ErrorBox error={meta.error} />}
        {!meta.data && <Btn className="w-full" disabled={meta.isPending} onClick={() => meta.mutate()}>{meta.isPending ? 'Creating…' : 'Generate keys'}</Btn>}
        {meta.data && (
          <div className="space-y-2">
            <p className="text-xs font-semibold text-red-600">{meta.data.warning}</p>
            {Object.entries(keys).map(([k, v]) => (
              <div key={k}><Row label={k.replace(/([A-Z])/g, ' $1').toLowerCase()} value={show(v)} mono /><Btn variant="ghost" className="w-full" onClick={() => void copy(show(v))}>Copy {k.replace(/([A-Z])/g, ' $1').toLowerCase()}</Btn></div>
            ))}
          </div>
        )}
      </Card>
      <SectionTitle>Private payout address</SectionTitle>
      <Card className="space-y-2">
        <Field label="Payee meta-address"><Input value={meta2} maxLength={160} onChange={(e) => setMeta2(e.target.value)} /></Field>
        <Field label="Payout reference"><Input value={ref} maxLength={128} onChange={(e) => setRef(e.target.value)} /></Field>
        {payout.isError && <ErrorBox error={payout.error} />}
        {payout.data && Object.entries(payout.data.payout).map(([k, v]) => <Row key={k} label={k.replace(/([A-Z])/g, ' $1').toLowerCase()} value={show(v)} mono />)}
        <Btn className="w-full" disabled={meta2.trim().length < 60 || !ref.trim() || payout.isPending} onClick={() => payout.mutate()}>Derive one-time address</Btn>
      </Card>
      <SectionTitle>Scan for payments (on this device)</SectionTitle>
      <Card className="space-y-2">
        <p className="text-xs text-suwappu-text-secondary">Announcements are downloaded and checked here in your browser. Your view key stays in memory on this device and is never sent anywhere. It is cleared when you leave this page or tap Clear.</p>
        <div className="grid grid-cols-2 gap-2"><Field label="Network"><Input value={chain} onChange={(e) => setChain(e.target.value)} /></Field><Field label="Start block" hint="Block number, decimal or 0x."><Input inputMode="numeric" value={from} onChange={(e) => setFrom(e.target.value)} /></Field></div>
        <Field label="View private key (0x…)"><Input type="password" autoComplete="off" value={vk} onChange={(e) => setVk(e.target.value)} /></Field>
        <Field label="Spend public key (0x…)"><Input value={sk} onChange={(e) => setSk(e.target.value)} /></Field>
        {local.error && <p className="text-xs text-red-500 break-words" role="alert">{local.error}</p>}
        {local.running && <p className="text-xs" role="status">Scanning from block {local.at ?? '…'} · {local.windows} {local.windows === 1 ? 'window' : 'windows'} checked · {local.seen} announcements</p>}
        {local.done && !local.error && <p className="text-xs font-semibold" role="status">{local.cancelled ? 'Stopped.' : 'Finished.'} Checked {local.seen} announcements.</p>}
        {local.matches.map((m) => <Row key={m.stealthAddress} label="Payment to" value={m.stealthAddress} mono />)}
        {local.done && local.matches.length === 0 && !local.error && <p className="text-xs text-suwappu-text-secondary">No payments found for this key in the scanned range.</p>}
        <div className="grid grid-cols-2 gap-2">
          {local.running ? <Btn variant="danger" onClick={() => { cancelRef.current = true }}>Cancel</Btn> : <Btn disabled={!toHexBlock(from) || !/^0x[0-9a-fA-F]{64}$/.test(vk.trim()) || !/^0x[0-9a-fA-F]{66}$/.test(sk.trim())} onClick={() => void runLocal()}>Scan here</Btn>}
          <Btn variant="ghost" disabled={local.running} onClick={() => { setVk(''); setLocal(INIT) }}>Clear</Btn>
        </div>
      </Card>
      <SectionTitle>Scan on our server (fallback)</SectionTitle>
      <Card className="space-y-2">
        <p className="text-xs font-semibold text-red-600">Warning: this sends your private view key to our server. Prefer scanning on this device above. Use this only if that does not work and you accept the server seeing the key.</p>
        <label className="flex items-start gap-2 text-xs min-h-[44px]"><input type="checkbox" className="mt-1" checked={armed} onChange={(e) => setArmed(e.target.checked)} /><span>I understand the server will see my view key.</span></label>
        <div className="grid grid-cols-2 gap-2"><Field label="Network"><Input value={chain} onChange={(e) => setChain(e.target.value)} /></Field><Field label="From block"><Input value={from} onChange={(e) => setFrom(e.target.value)} /></Field></div>
        <Field label="View private key (0x…)"><Input type="password" autoComplete="off" value={vk} onChange={(e) => setVk(e.target.value)} /></Field>
        <Field label="Spend public key (0x…)"><Input value={sk} onChange={(e) => setSk(e.target.value)} /></Field>
        {scan.isError && <ErrorBox error={scan.error} />}
        {scan.data && <pre className="text-[11px] whitespace-pre-wrap break-all bg-suwappu-sakura-mid/10 rounded-suwappu-lg p-2">{JSON.stringify(scan.data, null, 2)}</pre>}
        <Btn className="w-full" disabled={!armed || !/^0x[0-9a-fA-F]{64}$/.test(vk.trim()) || !/^0x[0-9a-fA-F]{66}$/.test(sk.trim()) || scan.isPending} onClick={() => scan.mutate()}>{scan.isPending ? 'Scanning…' : 'Scan'}</Btn>
      </Card>
      <SectionTitle>Compliance export</SectionTitle>
      <Card className="space-y-2">
        <p className="text-xs text-suwappu-text-secondary">Download a record of your private payouts for auditors.</p>
        {exp.isError && <ErrorBox error={exp.error} />}
        <Btn className="w-full" disabled={exp.isFetching} onClick={() => void exp.refetch()}>{exp.isFetching ? 'Preparing…' : 'Prepare export'}</Btn>
        {exp.data !== undefined && <Btn variant="ghost" className="w-full" onClick={download}>Download JSON</Btn>}
      </Card>
    </BankPage>
  )
}
