"""Bank M2 Earn + M3 Credit tables (mirrors api-ts db/schema/bankEarnCredit.ts + drizzle 0027)."""


def statements(is_sqlite: bool) -> list[str]:
    ts = "DATETIME DEFAULT CURRENT_TIMESTAMP" if is_sqlite else "TIMESTAMP DEFAULT NOW()"
    js = "TEXT" if is_sqlite else "JSONB"
    jd = "'{}'" if is_sqlite else "'{}'::jsonb"
    num = "NUMERIC" if is_sqlite else "NUMERIC(78,0)"
    return [
        f"""CREATE TABLE IF NOT EXISTS bank_earn_positions (
            savings_account_id TEXT PRIMARY KEY NOT NULL,
            owner_type varchar(24) NOT NULL,
            owner_id varchar(64) NOT NULL,
            checking_account_id text NOT NULL,
            chain varchar(32) NOT NULL,
            asset varchar(16) NOT NULL,
            vault varchar(64) NOT NULL,
            shares_minor {num} NOT NULL DEFAULT 0,
            pledged_shares_minor {num} NOT NULL DEFAULT 0,
            realized_yield_minor {num} NOT NULL DEFAULT 0,
            created_at {ts} NOT NULL,
            updated_at {ts} NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS bank_earn_ops (
            id TEXT PRIMARY KEY NOT NULL,
            owner_type varchar(24) NOT NULL,
            owner_id varchar(64) NOT NULL,
            idempotency_key varchar(160) NOT NULL,
            request_hash varchar(64) NOT NULL,
            kind varchar(12) NOT NULL,
            source varchar(12) NOT NULL DEFAULT 'manual',
            savings_account_id text NOT NULL,
            checking_account_id text NOT NULL,
            vault varchar(64) NOT NULL,
            chain varchar(32) NOT NULL,
            assets_minor {num} NOT NULL,
            shares_minor {num},
            status varchar(12) NOT NULL DEFAULT 'pending',
            tx_hash varchar(128),
            approve_tx_hash varchar(128),
            transfer_id text,
            failure_reason text,
            metadata {js} NOT NULL DEFAULT {jd},
            created_at {ts} NOT NULL,
            updated_at {ts} NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS bank_earn_settings (
            account_id TEXT PRIMARY KEY NOT NULL,
            owner_type varchar(24) NOT NULL,
            owner_id varchar(64) NOT NULL,
            enabled integer NOT NULL DEFAULT 1,
            floor_minor {num} NOT NULL DEFAULT 0,
            vault varchar(64) NOT NULL,
            min_sweep_minor {num} NOT NULL DEFAULT '1000000',
            last_sweep_period varchar(16),
            created_at {ts} NOT NULL,
            updated_at {ts} NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS bank_earn_snapshots (
            id TEXT PRIMARY KEY NOT NULL,
            savings_account_id text NOT NULL,
            vault varchar(64) NOT NULL,
            shares_minor {num} NOT NULL,
            principal_minor {num} NOT NULL,
            value_minor {num} NOT NULL,
            period varchar(16) NOT NULL,
            taken_at {ts} NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS bank_credit_lines (
            id TEXT PRIMARY KEY NOT NULL,
            owner_type varchar(24) NOT NULL,
            owner_id varchar(64) NOT NULL,
            kind varchar(20) NOT NULL,
            status varchar(12) NOT NULL DEFAULT 'active',
            chain varchar(32) NOT NULL,
            loan_asset varchar(16) NOT NULL,
            account_id text NOT NULL,
            market_id varchar(66),
            collateral_token varchar(64),
            collateral_decimals integer,
            collateral_savings_account_id text,
            collateral_minor {num} NOT NULL DEFAULT 0,
            pool_account_id text,
            limit_minor {num} NOT NULL DEFAULT 0,
            principal_minor {num} NOT NULL DEFAULT 0,
            accrued_interest_minor {num} NOT NULL DEFAULT 0,
            apr_bps integer NOT NULL DEFAULT 0,
            last_accrual_at {ts} NOT NULL,
            receivable_id varchar(64),
            face_minor {num},
            last_level varchar(10) NOT NULL DEFAULT 'ok',
            metadata {js} NOT NULL DEFAULT {jd},
            created_at {ts} NOT NULL,
            updated_at {ts} NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS bank_credit_events (
            id TEXT PRIMARY KEY NOT NULL,
            line_id text NOT NULL,
            owner_type varchar(24) NOT NULL,
            owner_id varchar(64) NOT NULL,
            type varchar(24) NOT NULL,
            level varchar(10) NOT NULL DEFAULT 'info',
            ltv_bps integer,
            health_factor_bps integer,
            data {js} NOT NULL DEFAULT {jd},
            created_at {ts} NOT NULL)""",
        f"""CREATE TABLE IF NOT EXISTS bank_credit_scores (
            id TEXT PRIMARY KEY NOT NULL,
            owner_type varchar(24) NOT NULL,
            owner_id varchar(64) NOT NULL,
            asset varchar(16) NOT NULL,
            chain varchar(32) NOT NULL,
            score integer NOT NULL,
            tier varchar(12) NOT NULL,
            proposed_limit_minor {num} NOT NULL,
            apr_bps integer NOT NULL,
            factors {js} NOT NULL DEFAULT {jd},
            computed_at {ts} NOT NULL)""",
        "CREATE INDEX IF NOT EXISTS ix_bank_earn_pos_owner ON bank_earn_positions(owner_type, owner_id)",
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_bank_earn_ops_idem ON bank_earn_ops(owner_type, owner_id, idempotency_key)",
        "CREATE INDEX IF NOT EXISTS ix_bank_earn_ops_status ON bank_earn_ops(status, updated_at)",
        "CREATE UNIQUE INDEX IF NOT EXISTS ux_bank_earn_snap_period ON bank_earn_snapshots(savings_account_id, vault, period)",
        "CREATE INDEX IF NOT EXISTS ix_bank_credit_lines_owner ON bank_credit_lines(owner_type, owner_id)",
        "CREATE INDEX IF NOT EXISTS ix_bank_credit_lines_kind ON bank_credit_lines(kind, status)",
        "CREATE INDEX IF NOT EXISTS ix_bank_credit_lines_recv ON bank_credit_lines(receivable_id)",
        "CREATE INDEX IF NOT EXISTS ix_bank_credit_events_owner ON bank_credit_events(owner_type, owner_id, created_at)",
        "CREATE INDEX IF NOT EXISTS ix_bank_credit_events_line ON bank_credit_events(line_id, created_at)",
        "CREATE INDEX IF NOT EXISTS ix_bank_credit_scores_owner ON bank_credit_scores(owner_type, owner_id, computed_at)",
    ]
